#Operadores aritméticos
# + = Adição | - = Subtração | * = Multiplicação | / = Divisão
# ** = potência | // = divisão inteira | % = resto da divisão
print (5+2)                 #Ordem de precedência
print (5-2)                 # 1 - () parenteses
print (5*2)                 # 2 - ** potências
print (5/2)                 # 3 - * \ % \\ - Multiplicação, divisão, resto de divisão, divisão inteira
print (5**2)                # 4 - + - -Adição e subtração
print (5//2)
print (5%2)
print (3*(5+4)**2)